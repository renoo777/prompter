/**
 * ★★★ 这个文件曾经装着整套「自绘悬停气泡」实现（`useHint` / `Hint` /
 *   `useBubblePos`，约 260 行）。第十一轮**全部删掉了**，用户的原话是
 *   「不行，还是删掉全部的提示吧」。
 *
 * # 为什么不留着（把话写全，否则下一个人会想把它加回来）
 *
 * 第四轮之前，界面靠**原生 `title`** 出提示 —— 用户说「特别特别 low」，
 * 对（那是系统白框：系统字体、系统配色，深色玻璃窗上唯一没被设计过的东西，
 * 也不为 560×360 的小窗避让，还要悬停 1 秒）。于是第十轮换成了自绘气泡，
 * 跟着主题走、能换行、会避让。**视觉问题解决了，但问题本身没解决。**
 *
 * 根因不是"气泡好不好看"，是**「鼠标扫过按钮就弹出东西」这件事本身**：
 *
 *   1. 它**遮住稿子**。截图里那团「开始提词 / 隐身 + 置顶 + 按当前的推进
 *      方式往下走…」把正文盖掉了三行 —— 在提词器上，盖住正文是最大的一宗罪：
 *      用户正在念的东西被一块浮层挡住了，而触发它只需要**鼠标路过**。
 *   2. 它**不受控**。提词时鼠标往往就停在窗口上，于是气泡会反复弹出来又收回去。
 *   3. 里面装的**不是用户当时需要的信息**。看气泡的人已经在看那个按钮了，
 *      他要的是"按下去会怎样"，而不是一段"这个功能的设计原理"。那是
 *      **给开发看的文档**，放错地方了。
 *
 * ⇒ 所以正确的做法不是"把气泡做得更小/更淡/更慢"，而是**一个都不留**：
 *   界面上所有说明文字一律删掉。「这个按钮是干什么的」由图标和位置说，
 *   「这个滑杆有什么用」由它右边的当前值说，剩下的属于 README。
 *
 * # 这条规则怎么被守住
 *
 * `scripts/check-tooltips.py` 会拒绝**任何**重新引入提示的写法：
 *   * 原生 `title=`（DOM 属性，不是组件 prop）
 *   * `useHint` / `Hint` / `tip-bubble` / `hint-ico` 任何一个名字
 *
 * ★ 判据是"**名字**"而不是"意图"：这个项目里除了提示没有别的用途会用到
 *   这几个名字，所以只要它们出现，就说明有人把提示加回来了。
 *   宁可误报让人来删这行门槛，也不要安静地漏掉 —— 这条是用户
 *   明确点名过的硬要求，不是风格偏好。
 *
 * ★★ 一个成立的反驳是：「那无障碍怎么办？」—— 无障碍用的是 `aria-label` /
 *    `aria-describedby`，那是**读屏**通道，不是视觉提示，**不受这条禁令约束**
 *    （而且本项目的 `aria-label` 一直都有）。两者不冲突。
 */

